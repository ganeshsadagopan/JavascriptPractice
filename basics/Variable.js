// let var and const are not data types, they are used to declare variables in JavaScript.


var a=10
console.log(a)
// This is a simple JavaScript program that declares a variable 'a' and assigns it the value of 10, then prints the value of 'a' to the console.

var b="ganesh"
var b =20
console.log(b)  
// Var alone can be redeclared, whereas let and const cannot be redeclared. 


console.log(c)
// This is a simple JavaScript program that declares a variable 'c' using the 'let' keyword and assigns it the value of 2.12, then prints the value of 'c' to the console.

const d='a'
console.log(d)
// This is a simple JavaScript program that declares a constant variable 'd' and assigns it the value of 3.14, then prints the value of 'd' to the console. Note that 'd' cannot be reassigned to a different value since it is declared as a constant. 


let booleanValue = true
console.log(booleanValue)
// This is a simple JavaScript program that declares a variable 'booleanValue' using the 'let' keyword and assigns it the boolean value of true, then prints the value of 'booleanValue' to the console.

